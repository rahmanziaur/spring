-- Run this script once in MySQL Workbench (or the mysql command line)
-- before starting the application.

-- 1. Create the database
CREATE DATABASE IF NOT EXISTS student_db;

-- 2. Select it
USE student_db;

-- 3. Create the table
CREATE TABLE IF NOT EXISTS students (
    id   INT          NOT NULL AUTO_INCREMENT,  -- primary key, generated by MySQL
    name VARCHAR(100) NULL,                     -- text up to 100 characters
    cgpa FLOAT        NULL,                     -- decimal number
    PRIMARY KEY (id)
);

-- 4. Sample data (optional)
INSERT INTO students (name, cgpa) VALUES
    ('Rahim Uddin',   3.75),
    ('Karima Akter',  3.90),
    ('Jamal Hossain', 3.42);

-- 5. Check
DESCRIBE students;
SELECT * FROM students;
